/**
 * Glitch Text Effect
 */

const mumaker = require('mumaker');
const config = require('../../config');

module.exports = {
  name: 'glitch',
  aliases: [],
  category: 'textmaker',
  description: 'Create glitch text effect',
  usage: '.glitch <text>',
  
  async execute(sock, msg, args, extra = {}) {
    try {
      const text = args.join(' ');
      const chatId = msg.key.remoteJid;
      
      if (!text) {
        return await sock.sendMessage(chatId, { 
          text: 'Please provide text to generate\nExample: .glitch Nick' 
        }, { quoted: extra?.quotedContact || msg });
      }
      
      const result = await mumaker.ephoto('https://en.ephoto360.com/create-digital-glitch-text-effects-online-767.html', text);
      
      if (!result || !result.image) {
        throw new Error('No image URL received from the API');
      }
      
      await sock.sendMessage(chatId, {
        image: { url: result.image },
        caption: `GENERATED BY ${config.botName}`
      }, { quoted: extra?.quotedContact || msg });
      
    } catch (error) {
      console.error('Error in glitch command:', error);
      await sock.sendMessage(msg.key.remoteJid, { 
        text: `Error: ${error.message}` 
      }, { quoted: extra?.quotedContact || msg });
    }
  }
};

